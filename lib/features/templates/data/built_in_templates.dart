List<ChatParticipant> _pair(String first, String second) => <ChatParticipant>[
      ChatParticipant(
        id: 'friend',
        name: first,
        initials: first.substring(0, 1).toUpperCase(),
        colorValue: 0xFFF09A65,
      ),
      ChatParticipant(
        id: 'me',
        name: second,
        initials: second.substring(0, 1).toUpperCase(),
        colorValue: 0xFF7058E7,
        side: MessageSide.outgoing,
      ),
    ];

List<TemplateMessageSeed> _lines(String a, String b, String c, [String? d]) =>
    <TemplateMessageSeed>[
      TemplateMessageSeed(senderId: 'me', side: MessageSide.outgoing, text: a),
      TemplateMessageSeed(senderId: 'friend', side: MessageSide.incoming, text: b),
      TemplateMessageSeed(senderId: 'me', side: MessageSide.outgoing, text: c),
      if (d != null)
        TemplateMessageSeed(senderId: 'friend', side: MessageSide.incoming, text: d),
    ];

